#!/usr/bin/env python3
"""Generate pipeline/CategoryKeywords.kt from the old FinSight category_mapping.json.

commonMain cannot read assets, so the JSON is embedded as a Kotlin map.
Usage (from finsight-app/):
  python3 scripts/gen_category_keywords.py \
    ../ref/finsight/finsight/scripts/training_data/processed/category_mapping.json \
    composeApp/src/commonMain/kotlin/com/finsight/pipeline/CategoryKeywords.kt
"""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
data = json.load(open(src))

# Old category id -> our domain.Category entry.
CATEGORY = {
    "food": "FOOD", "transport": "TRANSPORT", "shopping": "SHOPPING", "housing": "HOUSING",
    "utilities": "BILLS", "entertainment": "ENTERTAINMENT", "health": "HEALTH", "education": "EDUCATION",
    "financial": "FINANCIAL", "income": "INCOME", "transfer": "TRANSFER", "uncategorized": "OTHER",
}
# Per-keyword overrides where our taxonomy is finer than the old one.
OVERRIDE = {
    "groceries": "GROCERIES", "internet": "MOBILE", "phone": "MOBILE",
    "investment": "INVESTMENT", "flight": "TRAVEL",
}

lines = [
    "package com.finsight.pipeline",
    "",
    "import com.finsight.domain.Category",
    "",
    "// GENERATED by finsight-app/scripts/gen_category_keywords.py from the old FinSight",
    "// scripts/training_data/processed/category_mapping.json. Do not edit by hand.",
    "object CategoryKeywords {",
    "    /** Old category id -> keywords, verbatim from category_mapping.json. */",
    "    val raw: Map<String, List<String>> = mapOf(",
]
for cid, words in data.items():
    ws = ", ".join(json.dumps(w) for w in words)
    lines.append(f"        {json.dumps(cid)} to listOf({ws}),")
lines += [
    "    )",
    "",
    "    /** Old category id -> our Category. */",
    "    val categoryOf: Map<String, Category> = mapOf(",
]
for cid in data:
    lines.append(f"        {json.dumps(cid)} to Category.{CATEGORY[cid]},")
lines += [
    "    )",
    "",
    "    /** keyword -> Category (first occurrence wins; finer per-keyword overrides applied). */",
    "    val keywordCategory: Map<String, Category> = mapOf(",
]
seen = set()
for cid, words in data.items():
    for w in words:
        if w in seen:
            continue
        seen.add(w)
        lines.append(f"        {json.dumps(w)} to Category.{OVERRIDE.get(w, CATEGORY[cid])},")
lines += ["    )", "}", ""]
open(out, "w").write("\n".join(lines))
print(f"wrote {out}: {len(seen)} keywords")
